export function createI18n({ storage = window.localStorage, storageKey = "rogue-match3-lang" } = {}) {
  let currentLang = loadLanguage();

  function loadLanguage() {
    try {
      const saved = storage.getItem(storageKey);
      if (saved && I18N_TEXT[saved]) return saved;
    } catch {
      // ignore
    }
    return DEFAULT_LANGUAGE;
  }

  function saveLanguage() {
    try {
      storage.setItem(storageKey, currentLang);
    } catch {
      // ignore
    }
  }

  function setLanguage(lang) {
    if (!I18N_TEXT[lang]) return currentLang;
    currentLang = lang;
    saveLanguage();
    return currentLang;
  }

  function getLanguage() {
    return currentLang;
  }

  function t(key, params = {}) {
    const table = I18N_TEXT[currentLang] || I18N_TEXT[DEFAULT_LANGUAGE];
    const fallback = I18N_TEXT.en || {};
    let value = table[key] ?? fallback[key] ?? key;
    for (const [paramKey, paramValue] of Object.entries(params)) {
      value = value.replaceAll(`{${paramKey}}`, String(paramValue));
    }
    return value;
  }

  return { t, setLanguage, getLanguage, languages: Object.keys(I18N_TEXT) };
}
